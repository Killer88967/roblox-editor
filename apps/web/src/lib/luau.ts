let registered = false;

/**
 * Registers a "luau" language with Monaco (Lua plus Luau's extra syntax) and the Studio
 * color theme. Tokens: keywords, built-ins, properties, methods, function names, `self`,
 * booleans/nil, numbers, strings, comments (with TODO), and type annotations.
 */
export function registerLuau(monaco: Monaco) {
  if (registered) return;
  registered = true;
  defineStudioTheme(monaco);

  monaco.languages.register({ id: "luau", extensions: [".luau", ".lua"], aliases: ["Luau"] });

  monaco.languages.setLanguageConfiguration("luau", {
    comments: { lineComment: "--", blockComment: ["--[[", "]]"] },
    brackets: [
      ["{", "}"],
      ["[", "]"],
      ["(", ")"],
    ],
    autoClosingPairs: [
      { open: "{", close: "}" },
      { open: "[", close: "]" },
      { open: "(", close: ")" },
      { open: '"', close: '"', notIn: ["string"] },
      { open: "'", close: "'", notIn: ["string"] },
      { open: "`", close: "`", notIn: ["string"] },
    ],
    folding: {
      markers: { start: /^\s*--\s*#region\b/, end: /^\s*--\s*#endregion\b/ },
    },
    indentationRules: {
      // A line that opens a block (anywhere in it, not inside a comment) indents the next.
      increaseIndentPattern:
        /^((?!(--)).)*((\b(else|function|then|do|repeat)\b((?!\b(end|until)\b).)*)|(\{\s*))$/,
      decreaseIndentPattern: /^\s*((\b(elseif|else|end|until)\b)|(\})|(\)))/,
    },
  });

  monaco.languages.setMonarchTokensProvider("luau", {
    defaultToken: "",
    keywords: [
      "and",
      "break",
      "continue",
      "do",
      "else",
      "elseif",
      "end",
      "for",
      "function",
      "if",
      "in",
      "local",
      "not",
      "or",
      "repeat",
      "return",
      "then",
      "until",
      "while",
    ],
    // Globals, libraries and datatypes Studio colors as built-ins.
    builtins: [...GLOBALS, ...LIBRARIES, ...DATATYPES],
    libs: new RegExp(`(?:${[...LIBRARIES, ...DATATYPES].join("|")})(?![\\w])`),
    operators: [
      "+",
      "-",
      "*",
      "/",
      "//",
      "%",
      "^",
      "#",
      "==",
      "~=",
      "<=",
      ">=",
      "<",
      ">",
      "=",
      "+=",
      "-=",
      "*=",
      "/=",
      "//=",
      "%=",
      "^=",
      "..=",
      "..",
      "...",
      "->",
      "::",
      "?",
      "|",
      "&",
    ],
    symbols: /[=><!~?:&|+\-*/^%#.]+/,
    tokenizer: {
      root: [
        [/--\[(=*)\[/, { token: "comment", next: "@blockComment.$1" }],
        [
          /(--)(.*?)(\b(?:TODO|FIXME|NOTE|HACK|XXX)\b)(.*)$/,
          ["comment", "comment", "comment.todo", "comment"],
        ],
        [/--.*$/, "comment"],
        [/\[(=*)\[/, { token: "string", next: "@longString.$1" }],
        // function name(), function Module.name(), function Module:method()
        [/(function)(\s+)([A-Za-z_]\w*(?:\s*[.:]\s*[A-Za-z_]\w*)*)/, ["keyword", "", "function"]],
        [/(export)(\s+)(type)(\s+)([A-Za-z_]\w*)/, ["keyword", "", "keyword", "", "type"]],
        [/(type)(\s+)([A-Za-z_]\w*)(?=\s*(?:<[^>]*>)?\s*=)/, ["keyword", "", "type"]],
        // math.floor, Vector3.new, task.wait: the whole thing is a built-in.
        [/(@libs)(\s*)(\.)(\s*)([A-Za-z_]\w*)/, ["builtin", "", "delimiter", "", "builtin"]],
        // Calls through . or : are methods; other . accesses are properties.
        [/(\.)(\s*)([A-Za-z_]\w*)(?=\s*[("'`{])/, ["delimiter", "", "method"]],
        [/(:)(\s*)([A-Za-z_]\w*)(?=\s*[("'`{])/, ["delimiter", "", "method"]],
        [/(::|->)(\s*)([A-Za-z_]\w*)/, ["operator", "", "type"]],
        [/(\.)(\s*)([A-Za-z_]\w*)/, ["delimiter", "", "property"]],
        // Remaining `name: Type` is a type annotation.
        [/(:)(\s*)([A-Za-z_]\w*)/, ["delimiter", "", "type"]],
        [
          /[a-zA-Z_]\w*/,
          {
            cases: {
              "true|false": "constant.bool",
              nil: "constant.nil",
              self: "variable.self",
              "@keywords": "keyword",
              "@builtins": "builtin",
              "@default": "identifier",
            },
          },
        ],
        [/0[xX][0-9a-fA-F_]+/, "number.hex"],
        [/0[bB][01_]+/, "number"],
        [/\d[\d_]*(\.[\d_]*)?([eE][-+]?\d+)?/, "number"],
        [/\.\d[\d_]*([eE][-+]?\d+)?/, "number"],
        [/"/, { token: "string", next: '@string."' }],
        [/'/, { token: "string", next: "@string.'" }],
        [/`/, { token: "string", next: "@interp" }],
        [/[{}()[\]]/, "@brackets"],
        [/@symbols/, { cases: { "@operators": "operator", "@default": "" } }],
        [/[;,]/, "delimiter"],
      ],
      blockComment: [
        [
          /\](=*)\]/,
          { cases: { "$1==$S2": { token: "comment", next: "@pop" }, "@default": "comment" } },
        ],
        [/\b(?:TODO|FIXME|NOTE|HACK|XXX)\b/, "comment.todo"],
        [/[^\]TFNHX]+/, "comment"],
        [/./, "comment"],
      ],
      longString: [
        [
          /\](=*)\]/,
          { cases: { "$1==$S2": { token: "string", next: "@pop" }, "@default": "string" } },
        ],
        [/[^\]]+/, "string"],
        [/./, "string"],
      ],
      string: [
        [/\\./, "string.escape"],
        [/["']/, { cases: { "$#==$S2": { token: "string", next: "@pop" }, "@default": "string" } }],
        [/[^\\"']+/, "string"],
      ],
      // Backtick strings with {expressions}.
      interp: [
        [/\\./, "string.escape"],
        [/\{/, { token: "delimiter.interp", next: "@interpExpr" }],
        [/`/, { token: "string", next: "@pop" }],
        [/[^\\`{]+/, "string"],
      ],
      interpExpr: [[/\}/, { token: "delimiter.interp", next: "@pop" }], { include: "root" }],
    },
  });
}
