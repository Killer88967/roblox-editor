import type { Monaco } from "@monaco-editor/react";

let registered = false;

/** Registers a "luau" language with Monaco: Lua plus Luau's extra keywords and syntax. */
export function registerLuau(monaco: Monaco) {
  if (registered) return;
  registered = true;

  monaco.languages.register({ id: "luau", extensions: [".luau", ".lua"], aliases: ["Luau"] });

  monaco.languages.setLanguageConfiguration("luau", {
    comments: { lineComment: "--", blockComment: ["--[[", "]]"] },
    brackets: [
      ["{", "}"],
      ["[", "]"],
      ["(", ")"],
    ],
    autoClosingPairs: [
      { open: "{", close: "}" },
      { open: "[", close: "]" },
      { open: "(", close: ")" },
      { open: '"', close: '"', notIn: ["string"] },
      { open: "'", close: "'", notIn: ["string"] },
      { open: "`", close: "`", notIn: ["string"] },
    ],
    indentationRules: {
      increaseIndentPattern:
        /^\s*((\b(else|function|then|do|repeat)\b((?!\b(end|until)\b).)*)|(\{\s*))$/,
      decreaseIndentPattern: /^\s*((\b(elseif|else|end|until)\b)|(\})|(\)))/,
    },
  });

  monaco.languages.setMonarchTokensProvider("luau", {
    defaultToken: "",
    keywords: [
      "and",
      "break",
      "continue",
      "do",
      "else",
      "elseif",
      "end",
      "export",
      "false",
      "for",
      "function",
      "if",
      "in",
      "local",
      "nil",
      "not",
      "or",
      "repeat",
      "return",
      "then",
      "true",
      "type",
      "typeof",
      "until",
      "while",
    ],
    builtins: [
      "game",
      "workspace",
      "script",
      "plugin",
      "shared",
      "_G",
      "Enum",
      "Instance",
      "Vector2",
      "Vector3",
      "CFrame",
      "Color3",
      "BrickColor",
      "UDim",
      "UDim2",
      "Ray",
      "Region3",
      "TweenInfo",
      "NumberRange",
      "NumberSequence",
      "ColorSequence",
      "Rect",
      "math",
      "string",
      "table",
      "task",
      "coroutine",
      "os",
      "debug",
      "utf8",
      "bit32",
      "buffer",
      "print",
      "warn",
      "error",
      "assert",
      "require",
      "pairs",
      "ipairs",
      "next",
      "select",
      "tostring",
      "tonumber",
      "pcall",
      "xpcall",
      "setmetatable",
      "getmetatable",
      "rawget",
      "rawset",
      "rawequal",
      "unpack",
      "tick",
      "time",
      "wait",
      "spawn",
      "delay",
    ],
    operators: [
      "+",
      "-",
      "*",
      "/",
      "//",
      "%",
      "^",
      "#",
      "==",
      "~=",
      "<=",
      ">=",
      "<",
      ">",
      "=",
      "+=",
      "-=",
      "*=",
      "/=",
      "//=",
      "%=",
      "^=",
      "..=",
      "..",
      "...",
      "->",
      "::",
      "?",
      "|",
      "&",
    ],
    symbols: /[=><!~?:&|+\-*/^%#.]+/,
    tokenizer: {
      root: [
        [/--\[(=*)\[/, { token: "comment", next: "@blockComment.$1" }],
        [/--.*$/, "comment"],
        [/\[(=*)\[/, { token: "string", next: "@longString.$1" }],
        [
          /[a-zA-Z_]\w*/,
          { cases: { "@keywords": "keyword", "@builtins": "type", "@default": "identifier" } },
        ],
        [/0[xX][0-9a-fA-F_]+/, "number.hex"],
        [/0[bB][01_]+/, "number"],
        [/\d[\d_]*(\.[\d_]*)?([eE][-+]?\d+)?/, "number"],
        [/\.\d[\d_]*([eE][-+]?\d+)?/, "number"],
        [/"/, { token: "string", next: '@string."' }],
        [/'/, { token: "string", next: "@string.'" }],
        [/`/, { token: "string", next: "@interp" }],
        [/[{}()[\]]/, "@brackets"],
        [/@symbols/, { cases: { "@operators": "operator", "@default": "" } }],
        [/[;,]/, "delimiter"],
      ],
      blockComment: [
        [
          /\](=*)\]/,
          { cases: { "$1==$S2": { token: "comment", next: "@pop" }, "@default": "comment" } },
        ],
        [/./, "comment"],
      ],
      longString: [
        [
          /\](=*)\]/,
          { cases: { "$1==$S2": { token: "string", next: "@pop" }, "@default": "string" } },
        ],
        [/./, "string"],
      ],
      string: [
        [/\\./, "string.escape"],
        [/["']/, { cases: { "$#==$S2": { token: "string", next: "@pop" }, "@default": "string" } }],
        [/[^\\"']+/, "string"],
      ],
      // Backtick strings with {expressions}.
      interp: [
        [/\\./, "string.escape"],
        [/\{/, { token: "delimiter.bracket", next: "@interpExpr" }],
        [/`/, { token: "string", next: "@pop" }],
        [/[^\\`{]+/, "string"],
      ],
      interpExpr: [[/\}/, { token: "delimiter.bracket", next: "@pop" }], { include: "root" }],
    },
  });
}
