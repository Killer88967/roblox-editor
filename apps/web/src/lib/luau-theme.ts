import type { Monaco } from "@monaco-editor/react";

/** Roblox Studio's default dark script editor colors. */
export const STUDIO = {
  background: "#252525",
  text: "#CCCCCC",
  keyword: "#F86D7C",
  builtin: "#84D6F7",
  number: "#FFC600",
  bool: "#FFC600",
  nil: "#FFC600",
  string: "#ADF195",
  comment: "#666666",
  todo: "#FFFFFF",
  operator: "#CCCCCC",
  functionName: "#FDFBAC",
  method: "#FDFBAC",
  property: "#61A1F1",
  self: "#F86D7C",
  type: "#84D6F7",
  selection: "#0B5AAF",
  currentLine: "#2D3241",
  matchingWord: "#555555",
  findMatch: "#8D7600",
  error: "#FF4646",
  warning: "#FF7315",
  info: "#61A1F1",
  ruler: "#666666",
  whitespace: "#555555",
  lineNumber: "#7C7C7C",
} as const;

const hex = (c: string) => c.replace("#", "");

export const THEME = "roblox-studio-dark";

let defined = false;

/** Defines the Studio-colored Monaco theme (tokens, editor chrome and suggestion icons). */
export function defineStudioTheme(monaco: Monaco) {
  if (defined) return;
  defined = true;
  const c = STUDIO;
  monaco.editor.defineTheme(THEME, {
    base: "vs-dark",
    inherit: true,
    rules: [
      { token: "", foreground: hex(c.text) },
      { token: "identifier", foreground: hex(c.text) },
      { token: "comment", foreground: hex(c.comment) },
      { token: "comment.todo", foreground: hex(c.todo), fontStyle: "bold" },
      { token: "keyword", foreground: hex(c.keyword) },
      { token: "constant.bool", foreground: hex(c.bool) },
      { token: "constant.nil", foreground: hex(c.nil) },
      { token: "variable.self", foreground: hex(c.self) },
      { token: "builtin", foreground: hex(c.builtin) },
      { token: "type", foreground: hex(c.type), fontStyle: "italic" },
      { token: "number", foreground: hex(c.number) },
      { token: "string", foreground: hex(c.string) },
      { token: "string.escape", foreground: "D7FFC4" },
      { token: "delimiter.interp", foreground: hex(c.keyword) },
      { token: "operator", foreground: hex(c.operator) },
      { token: "delimiter", foreground: hex(c.operator) },
      { token: "function", foreground: hex(c.functionName) },
      { token: "method", foreground: hex(c.method) },
      { token: "property", foreground: hex(c.property) },
    ],
    colors: {
      "editor.background": c.background,
      "editor.foreground": c.text,
      "editorGutter.background": c.background,
      "editor.lineHighlightBackground": c.currentLine,
      "editor.lineHighlightBorder": "#00000000",
      "editor.selectionBackground": c.selection,
      "editor.inactiveSelectionBackground": `${c.selection}80`,
      "editor.selectionHighlightBackground": `${c.matchingWord}AA`,
      "editor.wordHighlightBackground": `${c.matchingWord}AA`,
      "editor.wordHighlightStrongBackground": `${c.matchingWord}CC`,
      "editor.findMatchBackground": c.findMatch,
      "editor.findMatchHighlightBackground": `${c.findMatch}80`,
      "editorCursor.foreground": "#FFFFFF",
      "editorLineNumber.foreground": c.lineNumber,
      "editorLineNumber.activeForeground": c.text,
      "editorIndentGuide.background1": "#3A3A3A",
      "editorIndentGuide.activeBackground1": "#5A5A5A",
      "editorWhitespace.foreground": c.whitespace,
      "editorRuler.foreground": c.ruler,
      "editorBracketMatch.background": `${c.matchingWord}80`,
      "editorBracketMatch.border": "#888888",
      "editorBracketHighlight.foreground1": "#FFD866",
      "editorBracketHighlight.foreground2": "#F86D7C",
      "editorBracketHighlight.foreground3": "#84D6F7",
      "editorBracketHighlight.unexpectedBracket.foreground": c.error,
      "editorError.foreground": c.error,
      "editorWarning.foreground": c.warning,
      "editorInfo.foreground": c.info,
      "editorHint.foreground": "#9E9E9E",
      "editorUnnecessaryCode.opacity": "#000000A0",
      "editorOverviewRuler.errorForeground": c.error,
      "editorOverviewRuler.warningForeground": c.warning,
      "editorOverviewRuler.border": "#00000000",
      "editorStickyScroll.background": c.background,
      "editorStickyScrollHover.background": "#2E2E2E",
      "editorWidget.background": "#2E2E2E",
      "editorWidget.border": "#454545",
      "editorSuggestWidget.background": "#2E2E2E",
      "editorSuggestWidget.border": "#454545",
      "editorSuggestWidget.foreground": c.text,
      "editorSuggestWidget.selectedBackground": c.selection,
      "editorSuggestWidget.selectedForeground": "#FFFFFF",
      "editorSuggestWidget.highlightForeground": c.builtin,
      "editorSuggestWidget.focusHighlightForeground": "#FFFFFF",
      "editorHoverWidget.background": "#2E2E2E",
      "editorHoverWidget.border": "#454545",
      "editorCodeLens.foreground": c.comment,
      "editorLink.activeForeground": c.builtin,
      "list.hoverBackground": "#3A3A3A",
      "list.activeSelectionBackground": c.selection,
      "list.highlightForeground": c.builtin,
      "scrollbarSlider.background": "#5A5A5A66",
      "scrollbarSlider.hoverBackground": "#6A6A6A99",
      "scrollbarSlider.activeBackground": "#7A7A7ACC",
      "input.background": "#1F1F1F",
      "input.border": "#454545",
      focusBorder: c.selection,
      "peekView.border": c.selection,
      "peekViewEditor.background": "#202020",
      "peekViewResult.background": "#2A2A2A",
      "peekViewTitle.background": "#2E2E2E",
      // Suggestion icons, matching the token colors of what they insert.
      "symbolIcon.propertyForeground": c.property,
      "symbolIcon.fieldForeground": c.string,
      "symbolIcon.methodForeground": c.method,
      "symbolIcon.functionForeground": c.functionName,
      "symbolIcon.eventForeground": c.number,
      "symbolIcon.variableForeground": c.text,
      "symbolIcon.constantForeground": c.bool,
      "symbolIcon.enumeratorForeground": c.builtin,
      "symbolIcon.enumeratorMemberForeground": c.number,
      "symbolIcon.classForeground": c.builtin,
      "symbolIcon.structForeground": c.builtin,
      "symbolIcon.interfaceForeground": c.type,
      "symbolIcon.moduleForeground": c.builtin,
      "symbolIcon.keywordForeground": c.keyword,
      "symbolIcon.snippetForeground": c.keyword,
      "symbolIcon.valueForeground": c.string,
      "symbolIcon.textForeground": c.text,
    },
  });
}
