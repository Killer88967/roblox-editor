#!/usr/bin/env bash
# Builds wasm/luau.wasm: the Luau VM and compiler (luau-lang/luau) plus the play-mode
# runtime (runtime/*.luau), for the browser.
#
# Needs clang/lld 18 and Ubuntu's wasm32 libc and libc++ packages:
#   sudo apt-get install clang-18 lld-18 wasi-libc libc++-18-dev-wasm32 libc++abi-18-dev-wasm32 \
#     libclang-rt-18-dev-wasm32
#
# Ubuntu's libc++abi is built without exceptions, which Luau's parser and compiler use, so
# the C++ ABI runtime is built here from LLVM's sources with WebAssembly exceptions.
set -euo pipefail

LUAU_VERSION=0.748
LLVM_VERSION=18.1.3

here=$(cd "$(dirname "$0")" && pwd)
build="$here/.build"
mkdir -p "$build/obj"

# Pinned to clang 18: it has to match Ubuntu's wasm32 libraries, and it keeps the output
# byte-for-byte the same everywhere (the built file is committed).
CLANG=$(command -v clang-18 || true)
CLANGXX=$(command -v clang++-18 || true)
if [ -z "$CLANG" ] || [ -z "$CLANGXX" ] || ! command -v wasm-ld-18 >/dev/null; then
  echo "build.sh needs clang-18 and lld-18 (apt-get install clang-18 lld-18 ...)" >&2
  exit 1
fi

if [ ! -d "$build/luau-$LUAU_VERSION" ]; then
  git -c advice.detachedHead=false clone -q --depth 1 --branch "$LUAU_VERSION" https://github.com/luau-lang/luau.git \
    "$build/luau-$LUAU_VERSION"
fi
if [ ! -d "$build/llvm-$LLVM_VERSION" ]; then
  git -c advice.detachedHead=false clone -q --depth 1 --filter=blob:none --sparse --branch "llvmorg-$LLVM_VERSION" \
    https://github.com/llvm/llvm-project.git "$build/llvm-$LLVM_VERSION"
  git -C "$build/llvm-$LLVM_VERSION" sparse-checkout set --no-cone \
    '/libcxxabi/src/' '/libcxxabi/include/' '/libunwind/src/' '/libunwind/include/' \
    '/libcxx/src/include/'
fi
luau="$build/luau-$LUAU_VERSION"
llvm="$build/llvm-$LLVM_VERSION"

# LLVM 18's libc++abi passes Wasm's destructor type (which returns its argument) where the
# other one is expected; fixed upstream later. Cast it through, keeping the real type.
cxa="$llvm/libcxxabi/src/cxa_exception.cpp"
if ! grep -q "rbxe:" "$cxa"; then
  sed -i \
    -e 's|  exception_header->exceptionDestructor = dest;|  exception_header->exceptionDestructor = reinterpret_cast<decltype(exception_header->exceptionDestructor)>(dest); // rbxe: wasm dtor type|' \
    -e 's|__cxa_init_primary_exception(thrown_object, tinfo, dest);|__cxa_init_primary_exception(thrown_object, tinfo, reinterpret_cast<void (*)(void*)>(dest)); // rbxe: wasm dtor type|' \
    "$cxa"
fi

# Ubuntu splits the wasm32 sysroot across /usr; point clang at just those parts so it never
# picks up the host's glibc headers.
sysroot="$build/sysroot"
mkdir -p "$sysroot/include" "$sysroot/lib"
ln -sfn /usr/include/wasm32-wasi "$sysroot/include/wasm32-wasi"
ln -sfn /usr/lib/wasm32-wasi "$sysroot/lib/wasm32-wasi"

# -ffile-prefix-map keeps local paths (from __FILE__ in asserts) out of the output, so CI
# builds the same bytes as anyone else.
common=(--target=wasm32-wasi "--sysroot=$sysroot" -O2 -fwasm-exceptions "-ffile-prefix-map=$here=."
  -ffunction-sections -fdata-sections -DNDEBUG -D_WASI_EMULATED_PROCESS_CLOCKS
  -D__USING_WASM_EXCEPTIONS__)

# Embed the runtime: one chunk per file, run in name order.
{
  echo '// Generated by build.sh from runtime/*.luau. Do not edit.'
  echo 'struct RuntimeChunk { const char* name; const char* source; };'
  echo 'extern const RuntimeChunk RUNTIME_CHUNKS[] = {'
  count=0
  for f in "$here"/runtime/*.luau; do
    name=$(basename "$f" .luau)
    printf '  {"=runtime/%s", R"LUAU_SRC(' "$name"
    cat "$f"
    echo ')LUAU_SRC"},'
    count=$((count + 1))
  done
  echo '};'
  echo "extern const int RUNTIME_CHUNK_COUNT = $count;"
} >"$build/runtime.cpp"

objects=()
pids=()
failed=0
compile() { # compile <source> <compiler> <flags...>
  local src=$1 cc=$2
  shift 2
  local obj="$build/obj/$(echo "$src" | sed "s|$build/||; s|$here/||; s|/|_|g").o"
  objects+=("$obj")
  if [ ! -f "$obj" ] || [ "$src" -nt "$obj" ]; then
    if [ "$(jobs -rp | wc -l)" -ge "$(nproc)" ]; then wait -n || failed=1; fi
    "$cc" "${common[@]}" "$@" -c "$src" -o "$obj" &
    pids+=($!)
  fi
}

luau_flags=(-std=c++17 -I"$luau/Common/include" -I"$luau/Ast/include" -I"$luau/Bytecode/include"
  -I"$luau/Compiler/include" -I"$luau/VM/include" -I"$luau/VM/src")
for src in "$luau"/Common/src/*.cpp "$luau"/Ast/src/*.cpp "$luau"/Bytecode/src/*.cpp "$luau"/Compiler/src/*.cpp "$luau"/VM/src/*.cpp; do
  compile "$src" "$CLANGXX" "${luau_flags[@]}"
done
compile "$here/src/bridge.cpp" "$CLANGXX" "${luau_flags[@]}"
# The type checker. src/shim has single-threaded <mutex> and <condition_variable>: this
# libc++ is built without threads.
analysis_flags=("${luau_flags[@]}" -D_WASI_EMULATED_MMAN -I"$here/src/shim"
  -I"$luau/Config/include" -I"$luau/Analysis/include")
for src in "$luau"/Config/src/*.cpp "$luau"/Analysis/src/*.cpp "$here/src/analysis.cpp"; do
  compile "$src" "$CLANGXX" "${analysis_flags[@]}"
done

abi_flags=(-std=c++20 -D_LIBCXXABI_BUILDING_LIBRARY -D_LIBCPP_BUILDING_LIBRARY
  -D_LIBCXXABI_HAS_NO_THREADS -DLIBCXXABI_SILENT_TERMINATE -D_LIBCPP_HAS_NO_THREADS
  -I"$llvm/libcxxabi/include" -I"$llvm/libunwind/include" -I"$llvm/libcxx/src")
for name in abort_message cxa_aux_runtime cxa_default_handlers cxa_exception \
  cxa_exception_storage cxa_guard cxa_handlers cxa_personality cxa_vector cxa_virtual \
  fallback_malloc private_typeinfo stdlib_exception stdlib_new_delete stdlib_stdexcept \
  stdlib_typeinfo; do
  compile "$llvm/libcxxabi/src/$name.cpp" "$CLANGXX" "${abi_flags[@]}"
done
compile "$llvm/libunwind/src/Unwind-wasm.c" "$CLANG" -D_LIBUNWIND_HIDE_SYMBOLS -I"$llvm/libunwind/include"
for pid in "${pids[@]}"; do wait "$pid" || failed=1; done
if [ "$failed" = 1 ]; then
  echo "compile failed" >&2
  exit 1
fi

# luau.wasm: the VM and play runtime. analysis.wasm: the type checker. Both share the rest.
play=()
analysis=()
for obj in "${objects[@]}"; do
  case "$obj" in
    *_Analysis_src_* | *_Config_src_* | *src_analysis.cpp.o) analysis+=("$obj") ;;
    *src_bridge.cpp.o | */runtime.cpp.o) play+=("$obj") ;;
    *) play+=("$obj") analysis+=("$obj") ;;
  esac
done

link() { # link <output> <objects...>
  local out=$1
  shift
  "$CLANGXX" --target=wasm32-wasi "--sysroot=$sysroot" -fwasm-exceptions -mexec-model=reactor \
    -nostdlib++ -O2 -Wl,--gc-sections -Wl,--strip-all \
    "$@" "$sysroot/lib/wasm32-wasi/libc++.a" -lwasi-emulated-process-clocks \
    -lwasi-emulated-mman -o "$here/wasm/$out"
  echo "built $(du -h "$here/wasm/$out" | cut -f1) wasm/$out (Luau $LUAU_VERSION)"
}

mkdir -p "$here/wasm"
link luau.wasm "${play[@]}"
link analysis.wasm "${analysis[@]}"
